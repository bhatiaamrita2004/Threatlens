CREATE TABLE app_users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(64)  NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role          VARCHAR(16)  NOT NULL
);

CREATE TABLE security_events (
    event_id         VARCHAR(64) PRIMARY KEY,
    user_id          VARCHAR(64) NOT NULL,
    source_ip        VARCHAR(64) NOT NULL,
    event_type       VARCHAR(32) NOT NULL,
    status           VARCHAR(16) NOT NULL,
    occurred_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    location         VARCHAR(64),
    destination_port INTEGER,
    scenario         VARCHAR(64)
);
CREATE INDEX idx_events_user_time ON security_events (user_id, occurred_at);
CREATE INDEX idx_events_time      ON security_events (occurred_at);

CREATE TABLE incidents (
    incident_id  VARCHAR(100) PRIMARY KEY,
    max_score    INTEGER NOT NULL,
    band         VARCHAR(16) NOT NULL,
    first_seen   TIMESTAMP WITH TIME ZONE NOT NULL,
    last_seen    TIMESTAMP WITH TIME ZONE NOT NULL,
    window_count INTEGER NOT NULL,
    explanation  VARCHAR(2000)
);
CREATE INDEX idx_incidents_score ON incidents (max_score);

CREATE TABLE incident_users (
    incident_id VARCHAR(100) NOT NULL REFERENCES incidents (incident_id) ON DELETE CASCADE,
    user_id     VARCHAR(64)  NOT NULL,
    PRIMARY KEY (incident_id, user_id)
);

CREATE TABLE incident_source_ips (
    incident_id VARCHAR(100) NOT NULL REFERENCES incidents (incident_id) ON DELETE CASCADE,
    source_ip   VARCHAR(64)  NOT NULL,
    PRIMARY KEY (incident_id, source_ip)
);

CREATE TABLE incident_rules (
    incident_id VARCHAR(100) NOT NULL REFERENCES incidents (incident_id) ON DELETE CASCADE,
    rule_name   VARCHAR(64)  NOT NULL,
    PRIMARY KEY (incident_id, rule_name)
);

CREATE TABLE alerts (
    alert_id    VARCHAR(100) PRIMARY KEY,
    rule_name   VARCHAR(64)  NOT NULL,
    severity    VARCHAR(16)  NOT NULL,
    score       INTEGER      NOT NULL,
    band        VARCHAR(16)  NOT NULL,
    reason      VARCHAR(512) NOT NULL,
    explanation VARCHAR(2000),
    user_id     VARCHAR(64),
    source_ip   VARCHAR(64),
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
    status      VARCHAR(16)  NOT NULL,
    incident_id VARCHAR(100)
);
CREATE INDEX idx_alerts_band_status ON alerts (band, status);
CREATE INDEX idx_alerts_status      ON alerts (status);
CREATE INDEX idx_alerts_incident    ON alerts (incident_id);
CREATE INDEX idx_alerts_occurred    ON alerts (occurred_at);

CREATE TABLE alert_evidence (
    alert_id VARCHAR(100) NOT NULL REFERENCES alerts (alert_id) ON DELETE CASCADE,
    event_id VARCHAR(64)  NOT NULL,
    PRIMARY KEY (alert_id, event_id)
);
CREATE INDEX idx_evidence_event ON alert_evidence (event_id);

CREATE TABLE analyst_feedback (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alert_id   VARCHAR(100) NOT NULL REFERENCES alerts (alert_id) ON DELETE CASCADE,
    analyst    VARCHAR(64)  NOT NULL,
    verdict    VARCHAR(24)  NOT NULL,
    note       VARCHAR(1000),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_feedback_alert ON analyst_feedback (alert_id, created_at);
