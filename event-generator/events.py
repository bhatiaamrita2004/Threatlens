"""SecurityEvent schema for ThreatLens (Phase 1).

Every event generated by ThreatLens uses this structure, so later phases
(validation, rules, features, ML) can rely on the same fields.
"""

from __future__ import annotations

import uuid
from dataclasses import asdict, dataclass, field
from datetime import datetime

EVENT_TYPES = {
    "LOGIN_SUCCESS",
    "LOGIN_FAILED",
    "CONNECTION_ATTEMPT",
    "API_REQUEST",
    "PRIVILEGE_CHANGE",
    "RESOURCE_ACCESS",
}
STATUSES = {"SUCCESS", "FAILURE", "INFO"}


@dataclass
class SecurityEvent:
    user_id: str
    source_ip: str
    event_type: str
    status: str
    timestamp: datetime
    location: str = "unknown"
    destination_ip: str | None = None
    destination_port: int | None = None
    protocol: str | None = None
    event_id: str = field(default_factory=lambda: str(uuid.uuid4()))
    metadata: dict = field(default_factory=lambda: {"synthetic": True, "scenario": "normal"})

    def __post_init__(self) -> None:
        if self.event_type not in EVENT_TYPES:
            raise ValueError(f"Unknown event_type: {self.event_type}")
        if self.status not in STATUSES:
            raise ValueError(f"Unknown status: {self.status}")
        if self.timestamp.tzinfo is None:
            raise ValueError("timestamp must be timezone-aware")

    def to_dict(self) -> dict:
        data = asdict(self)
        data["timestamp"] = self.timestamp.isoformat()
        return data